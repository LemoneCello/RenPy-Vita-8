"""Image stage: downscale a game's images and make Ren'Py draw them at full size.

Reads an extracted game/ tree and writes an overlay directory holding only the
downscaled images (same paths and filenames) plus vita_oversample.rpy. That
script hooks Ren'Py's Image so every listed file gets oversample=1/<factor>, so
layout written for 1920x1080 stays the same without editing the game's scripts.

Small images are left alone: they save little memory, and many are Frame()
sources whose pixel borders would need changing too.

Images with alpha whose visible part covers less than --trim-below of the
image (full-screen button and overlay images, mostly transparent) are also
cropped to that part. The hook pads them back to their full size with fully
transparent pixels when Ren'Py loads them, so they display exactly as before
but decode much faster (on the Vita, a full-screen 960x540 PNG took ~120 ms
to decode whatever its content). Ren'Py treats the cropped-away pixels as
zero after premultiplying anyway.
"""

import argparse
import math
import shutil
import sys
from concurrent.futures import ProcessPoolExecutor
from pathlib import Path, PurePosixPath

from PIL import Image

IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp"}
HOOK_NAME = "vita_oversample.rpy"

HOOK_TEMPLATE = '''\
# Generated by vita_images.py. Files in `table` were downscaled; the oversample
# value shown tells Ren'Py to draw them at their original size. Files in
# `trimmed` were cropped to their visible part; loading pads them back to
# (width, height) with the crop at (left, top), so they look the same.

python early:

    def _vita_install_oversample():
        import renpy.display.im as im

        table = {{
{entries}
        }}

        trimmed = {{
{trims}
        }}

        resolved = {{ }}

        def prefixes():
            # Where Ren'Py looks for an image file: config.search_prefixes,
            # then (Ren'Py 8.1+) the images directory, so the game can write
            # "gallery/x.png" for images/gallery/x.png.
            try:
                return renpy.loader.get_prefixes(tl=False, directory="images")
            except Exception:
                return getattr(renpy.config, "search_prefixes", None) or [ "" ]

        def resolve(filename):
            """
            The table key of the file Ren'Py loads for a file name as the game
            writes it, or None.
            """

            name = filename.replace("\\\\", "/")
            rv = resolved.get(name, False)
            if rv is not False:
                return rv

            rv = None
            for prefix in prefixes():
                path = prefix + name
                key = path.lower()
                if key in table or key in trimmed:
                    rv = key
                    break
                # The first prefix with an existing file wins, as in the loader.
                try:
                    if renpy.loader.loadable(path, tl=False):
                        break
                except TypeError:
                    if renpy.loader.loadable(path):
                        break
                except Exception:
                    return None

            resolved[name] = rv
            return rv

        original_init = im.Image.__init__

        def __init__(self, filename, *args, **properties):
            if isinstance(filename, str):
                factor = table.get(resolve(filename))
                if factor is not None:
                    properties.setdefault("oversample", factor)
            original_init(self, filename, *args, **properties)

        im.Image.__init__ = __init__

        original_load = im.Image.load

        def load(self, *args, **kwargs):
            surf = original_load(self, *args, **kwargs)

            filename = self.filename
            if not isinstance(filename, str):
                return surf

            trim = trimmed.get(resolve(filename))
            if trim is None:
                return surf

            left, top, width, height = trim
            w, h = surf.get_size()
            if (w, h) == (width, height):
                return surf

            # A straight copy (no blending) into a new, zeroed surface.
            full = renpy.display.pgrender.surface((width, height), True)
            renpy.display.accelerator.nogil_copy(surf, full.subsurface((left, top, w, h)))

            # The crop is the visible part, so the image cache needn't scan
            # the padded surface for it (where the eboot's Ren'Py has
            # im.known_bounds).
            known = getattr(im, "known_bounds", None)
            if known is not None:
                known[full] = (left, top, w, h)

            return full

        im.Image.load = load

    _vita_install_oversample()
'''


def find_images(src, prefixes):
    for path in sorted(src.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in IMAGE_EXTS:
            continue
        rel = PurePosixPath(path.relative_to(src).as_posix())
        if prefixes and not any(str(rel).startswith(p) for p in prefixes):
            continue
        yield rel


def process(job):
    """Downscale one image. Returns (rel, status, old_size, new_size, trim)."""
    src, dest, rel, factor, min_pixels, jpeg_quality, trim_below = job
    with Image.open(src / rel) as img:
        img.load()
        w, h = img.size
        if w * h < min_pixels:
            return rel, "small", (w, h), None, None

        new_size = (math.ceil(w / factor), math.ceil(h / factor))
        fmt = img.format
        if img.mode in ("RGBA", "LA", "P", "PA") and fmt != "JPEG":
            # Resize premultiplied so transparent edges don't pick up dark fringes.
            out = img.convert("RGBA").convert("RGBa").resize(new_size, Image.LANCZOS).convert("RGBA")
        else:
            out = img.convert("RGB").resize(new_size, Image.LANCZOS)

    # Crop mostly transparent images to their visible part.
    trim = None
    if out.mode == "RGBA" and fmt != "JPEG":
        bbox = out.getchannel("A").getbbox() or (0, 0, 1, 1)
        left, top, right, bottom = bbox
        if (right - left) * (bottom - top) < trim_below * new_size[0] * new_size[1]:
            out = out.crop(bbox)
            trim = (left, top, new_size[0], new_size[1])

    target = dest / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "JPEG":
        out.save(target, "JPEG", quality=jpeg_quality, optimize=True)
    elif fmt == "WEBP":
        out.save(target, "WEBP", lossless=True)
    else:
        out.save(target, "PNG", optimize=True)
    return rel, "scaled", (w, h), new_size, trim


def write_hook(dest, scaled, factor, trims):
    # Ren'Py's oversample is file pixels per virtual pixel, so a file shrunk by
    # `factor` needs 1/factor to be drawn at its original size.
    entries = "\n".join(f'            "{str(rel).lower()}": {1 / factor!r},' for rel in sorted(scaled))
    trim_entries = "\n".join(f'            "{str(rel).lower()}": {trims[rel]!r},' for rel in sorted(trims))
    (dest / HOOK_NAME).write_text(HOOK_TEMPLATE.format(entries=entries, trims=trim_entries), encoding="utf-8")


def mib(n):
    return f"{n / 2**20:.1f} MiB"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src", type=Path, default=Path("build/phase0/game"), help="extracted game/ directory")
    parser.add_argument("--dest", type=Path, default=Path("build/images/game"), help="overlay output directory")
    parser.add_argument("--only", action="append", default=[], metavar="PREFIX",
                        help="only process paths starting with PREFIX (repeatable), e.g. gui/")
    parser.add_argument("--factor", type=int, default=2, help="downscale factor (default 2)")
    parser.add_argument("--min-pixels", type=int, default=256 * 256,
                        help="leave images with fewer pixels than this untouched")
    parser.add_argument("--jpeg-quality", type=int, default=90)
    parser.add_argument("--trim-below", type=float, default=0.6,
                        help="crop images with alpha whose visible part covers less than this share of the image (0 turns cropping off)")
    parser.add_argument("--jobs", type=int, default=None, help="worker processes (default: CPU count)")
    parser.add_argument("--dry-run", action="store_true", help="only list what would be processed")
    args = parser.parse_args()

    if not args.src.is_dir():
        sys.exit(f"{args.src} is not a directory")
    rels = list(find_images(args.src, args.only))
    print(f"{len(rels)} images under {args.src}" + (f" matching {args.only}" if args.only else ""))
    if args.dry_run:
        for rel in rels:
            print(f"  {rel}")
        return

    if args.dest.exists():
        shutil.rmtree(args.dest)
    args.dest.mkdir(parents=True)

    jobs = [(args.src, args.dest, rel, args.factor, args.min_pixels, args.jpeg_quality, args.trim_below) for rel in rels]
    scaled, small, odd = [], 0, 0
    trims = {}
    before = after = 0
    with ProcessPoolExecutor(args.jobs) as pool:
        for rel, status, (w, h), new, trim in pool.map(process, jobs, chunksize=8):
            if status == "small":
                small += 1
                continue
            scaled.append(rel)
            if trim is not None:
                trims[rel] = trim
            odd += bool(w % args.factor or h % args.factor)
            before += w * h * 4
            after += new[0] * new[1] * 4

    write_hook(args.dest, scaled, args.factor, trims)

    print(f"Scaled {len(scaled)}, left {small} small images untouched; cropped {len(trims)} mostly transparent ones")
    if odd:
        print(f"  {odd} had dimensions not divisible by {args.factor}; they now display up to 1 px larger")
    print(f"Decoded texture size of scaled images: {mib(before)} -> {mib(after)}")
    disk = sum(p.stat().st_size for p in args.dest.rglob("*") if p.is_file())
    print(f"Overlay written to {args.dest} ({mib(disk)} on disk, includes {HOOK_NAME})")


if __name__ == "__main__":
    main()
