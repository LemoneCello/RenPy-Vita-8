"""Image stage: downscale a game's images and make Ren'Py draw them at full size.

Reads an extracted game/ tree and writes an overlay directory holding only the
downscaled images (same paths and filenames) plus vita_oversample.rpy. That
script hooks Ren'Py's Image so every listed file gets oversample=1/<factor>, so
the game's layout stays the same without editing its scripts.

The factor makes the game's screen fit the Vita's (960x544), the way Ren'Py
scales it there: the game's size (gui.init(W, H) or config.screen_width and
screen_height in its scripts) divided by the Vita's, for the side that limits.
1920x1080 games: 2 (full-screen images become 960x540); 1280x720: 4/3; games
already that small or smaller: nothing to shrink (only the cropping below).
Every large image shrinks by the same factor, so each keeps its size relative
to the screen. --factor overrides it.

Small images are left alone: they save little memory, and many are Frame()
sources whose pixel borders would need changing too.

Images with alpha whose visible part covers less than --trim-below of the
image (full-screen button and overlay images, mostly transparent) are also
cropped to that part. The hook pads them back to their full size with fully
transparent pixels when Ren'Py loads them, so they display exactly as before
but decode much faster (on the Vita, a full-screen 960x540 PNG took ~120 ms
to decode whatever its content). Ren'Py treats the cropped-away pixels as
zero after premultiplying anyway.
"""

import argparse
import json
import math
import re
import shutil
import sys
from concurrent.futures import ProcessPoolExecutor
from fractions import Fraction
from pathlib import Path, PurePosixPath

from PIL import Image

from vita_common import progress

IMAGE_EXTS = {".png", ".jpg", ".jpeg", ".webp"}
VITA_SCREEN = (960, 544)

# gui.init(1920, 1080), or config.screen_width = 1920 (define'd or assigned).
GUI_INIT_RE = re.compile(r"^\s*gui\.init\(\s*(\d+)\s*,\s*(\d+)\s*\)", re.M)
SCREEN_SIZE_RE = re.compile(r"^\s*(?:define\s+)?config\.screen_(width|height)\s*=\s*(\d+)\s*$", re.M)
HOOK_NAME = "vita_oversample.rpy"

HOOK_TEMPLATE = '''\
# Generated by vita_images.py. Files in `table` were downscaled; the oversample
# value shown tells Ren'Py to draw them at their original size. Files in
# `trimmed` were cropped to their visible part; loading pads them back to
# (width, height) with the crop at (left, top), so they look the same.

python early:

    def _vita_install_oversample():
        import renpy.display.im as im

        table = {{
{entries}
        }}

        trimmed = {{
{trims}
        }}

        resolved = {{ }}

        def prefixes():
            # Where Ren'Py looks for an image file: config.search_prefixes,
            # then (Ren'Py 8.1+) the images directory, so the game can write
            # "gallery/x.png" for images/gallery/x.png.
            try:
                return renpy.loader.get_prefixes(tl=False, directory="images")
            except Exception:
                return getattr(renpy.config, "search_prefixes", None) or [ "" ]

        def resolve(filename):
            """
            The table key of the file Ren'Py loads for a file name as the game
            writes it, or None.
            """

            name = filename.replace("\\\\", "/")
            rv = resolved.get(name, False)
            if rv is not False:
                return rv

            rv = None
            for prefix in prefixes():
                path = prefix + name
                key = path.lower()
                if key in table or key in trimmed:
                    rv = key
                    break
                # The first prefix with an existing file wins, as in the loader.
                try:
                    if renpy.loader.loadable(path, tl=False):
                        break
                except TypeError:
                    if renpy.loader.loadable(path):
                        break
                except Exception:
                    return None

            resolved[name] = rv
            return rv

        original_init = im.Image.__init__

        def __init__(self, filename, *args, **properties):
            if isinstance(filename, str):
                factor = table.get(resolve(filename))
                if factor is not None:
                    properties.setdefault("oversample", factor)
            original_init(self, filename, *args, **properties)

        im.Image.__init__ = __init__

        original_load = im.Image.load

        def load(self, *args, **kwargs):
            surf = original_load(self, *args, **kwargs)

            filename = self.filename
            if not isinstance(filename, str):
                return surf

            trim = trimmed.get(resolve(filename))
            if trim is None:
                return surf

            left, top, width, height = trim
            w, h = surf.get_size()
            if (w, h) == (width, height):
                return surf

            # A straight copy (no blending) into a new, zeroed surface.
            full = renpy.display.pgrender.surface((width, height), True)
            renpy.display.accelerator.nogil_copy(surf, full.subsurface((left, top, w, h)))

            # The crop is the visible part, so the image cache needn't scan
            # the padded surface for it (where the eboot's Ren'Py has
            # im.known_bounds).
            known = getattr(im, "known_bounds", None)
            if known is not None:
                known[full] = (left, top, w, h)

            return full

        im.Image.load = load

    _vita_install_oversample()
'''


def find_images(src, prefixes):
    for path in sorted(src.rglob("*")):
        if not path.is_file() or path.suffix.lower() not in IMAGE_EXTS:
            continue
        rel = PurePosixPath(path.relative_to(src).as_posix())
        if prefixes and not any(str(rel).startswith(p) for p in prefixes):
            continue
        yield rel


def game_size(game_dir):
    """The game's screen size from its scripts, or None if they don't say."""
    found = {}
    for path in sorted(game_dir.rglob("*.rpy")):
        text = path.read_text(encoding="utf-8", errors="replace")
        if m := GUI_INIT_RE.search(text):
            return int(m.group(1)), int(m.group(2))
        for key, value in SCREEN_SIZE_RE.findall(text):
            found.setdefault(key, int(value))
    if "width" in found and "height" in found:
        return found["width"], found["height"]
    return None


def auto_factor(size):
    """How much to shrink images so the game's screen fits the Vita's; at least 1."""
    w, h = size
    return max(Fraction(w, VITA_SCREEN[0]), Fraction(h, VITA_SCREEN[1]), Fraction(1))


def parse_factor(text):
    try:
        factor = Fraction(text)
    except (ValueError, ZeroDivisionError):
        raise argparse.ArgumentTypeError(f"{text!r} isn't a number or fraction like 4/3")
    if factor < 1:
        raise argparse.ArgumentTypeError("the factor must be at least 1")
    return factor


def process(job):
    """Downscale one image. Returns (rel, status, old_size, new_size, trim)."""
    src, dest, rel, factor, min_pixels, jpeg_quality, trim_below = job
    with Image.open(src / rel) as img:
        img.load()
        w, h = img.size
        if w * h < min_pixels:
            return rel, "small", (w, h), None, None

        new_size = (math.ceil(Fraction(w) / factor), math.ceil(Fraction(h) / factor))
        fmt = img.format
        has_alpha = img.mode in ("RGBA", "LA", "P", "PA") and fmt != "JPEG"
        if new_size == (w, h):
            # Nothing to shrink (factor 1): only cropping can help, and only with alpha.
            if not has_alpha:
                return rel, "small", (w, h), None, None
            out = img.convert("RGBA")
        elif has_alpha:
            # Resize premultiplied so transparent edges don't pick up dark fringes.
            out = img.convert("RGBA").convert("RGBa").resize(new_size, Image.LANCZOS).convert("RGBA")
        else:
            out = img.convert("RGB").resize(new_size, Image.LANCZOS)

    # Crop mostly transparent images to their visible part.
    trim = None
    if out.mode == "RGBA" and fmt != "JPEG":
        bbox = out.getchannel("A").getbbox() or (0, 0, 1, 1)
        left, top, right, bottom = bbox
        if (right - left) * (bottom - top) < trim_below * new_size[0] * new_size[1]:
            out = out.crop(bbox)
            trim = (left, top, new_size[0], new_size[1])
    if new_size == (w, h) and trim is None:
        return rel, "small", (w, h), None, None

    target = dest / rel
    target.parent.mkdir(parents=True, exist_ok=True)
    if fmt == "JPEG":
        out.save(target, "JPEG", quality=jpeg_quality, optimize=True)
    elif fmt == "WEBP":
        out.save(target, "WEBP", lossless=True)
    else:
        out.save(target, "PNG", optimize=True)
    return rel, "scaled", (w, h), new_size, trim


def write_hook(dest, scaled, factor, trims):
    # Ren'Py's oversample is file pixels per virtual pixel, so a file shrunk by
    # `factor` needs 1/factor to be drawn at its original size.
    entries = "\n".join(f'            "{str(rel).lower()}": {float(1 / factor)!r},' for rel in sorted(scaled))
    trim_entries = "\n".join(f'            "{str(rel).lower()}": {trims[rel]!r},' for rel in sorted(trims))
    text = HOOK_TEMPLATE.format(entries=entries, trims=trim_entries)
    hook = dest / HOOK_NAME
    # Rewritten only when it changes, so unchanged builds stay unchanged.
    if not hook.exists() or hook.read_text(encoding="utf-8") != text:
        hook.write_text(text, encoding="utf-8")


def mib(n):
    return f"{n / 2**20:.1f} MiB"


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--src", type=Path, default=Path("build/phase0/game"), help="extracted game/ directory")
    parser.add_argument("--dest", type=Path, default=Path("build/images/game"), help="overlay output directory")
    parser.add_argument("--only", action="append", default=[], metavar="PREFIX",
                        help="only process paths starting with PREFIX (repeatable), e.g. gui/")
    parser.add_argument("--factor", type=parse_factor,
                        help="downscale factor, e.g. 2 or 4/3 (default: from the game's screen size)")
    parser.add_argument("--min-pixels", type=int, default=256 * 256,
                        help="leave images with fewer pixels than this untouched")
    parser.add_argument("--jpeg-quality", type=int, default=90)
    parser.add_argument("--trim-below", type=float, default=0.6,
                        help="crop images with alpha whose visible part covers less than this share of the image (0 turns cropping off)")
    parser.add_argument("--jobs", type=int, default=None, help="worker processes (default: CPU count)")
    parser.add_argument("--dry-run", action="store_true", help="only list what would be processed")
    args = parser.parse_args()

    if not args.src.is_dir():
        sys.exit(f"{args.src} is not a directory")
    rels = list(find_images(args.src, args.only))
    print(f"{len(rels)} images under {args.src}" + (f" matching {args.only}" if args.only else ""))
    if args.dry_run:
        for rel in rels:
            print(f"  {rel}")
        return

    if args.factor is None:
        size = game_size(args.src)
        if size is None:
            sys.exit("The game's scripts don't give its screen size (gui.init(W, H) or config.screen_width\n"
                     "and screen_height); pass --factor, e.g. --factor 1 to leave image sizes alone")
        args.factor = auto_factor(size)
        exact = "" if args.factor.denominator == 1 else f" ({float(args.factor):.3g})"
        print(f"Game screen {size[0]}x{size[1]}: shrinking images by {args.factor}{exact}"
              if args.factor > 1 else f"Game screen {size[0]}x{size[1]} fits the Vita's: only cropping")

    # Incremental, like the extract and video stages: a record next to the
    # overlay (not in it, so it isn't shipped) keeps each image's source size
    # and modification time and its result. Images that haven't changed since
    # are kept; different settings start over.
    settings = {"factor": str(args.factor) if args.factor.denominator != 1 else int(args.factor), "min_pixels": args.min_pixels, "jpeg_quality": args.jpeg_quality,
                "trim_below": args.trim_below}
    record_path = args.dest.parent / f"{args.dest.name}.images.json"
    try:
        record = json.loads(record_path.read_text())
    except (OSError, ValueError):
        record = {}
    if record.get("settings") != settings:
        record = {"settings": settings, "files": {}}
        if args.dest.exists():
            shutil.rmtree(args.dest)
    args.dest.mkdir(parents=True, exist_ok=True)
    old = record["files"]

    results, todo = {}, []
    for rel in rels:
        st = (args.src / rel).stat()
        entry = old.get(str(rel))
        if (entry and entry["mtime"] == st.st_mtime_ns and entry["bytes"] == st.st_size
                and (entry["status"] == "small" or (args.dest / rel).exists())):
            results[rel] = entry
        else:
            todo.append(rel)

    # Outputs whose image is gone or is now left untouched.
    wanted = {str(rel) for rel, e in results.items() if e["status"] == "scaled"} | {str(rel) for rel in todo}
    stale = [p for p in args.dest.rglob("*")
             if p.is_file() and p.name != HOOK_NAME and str(p.relative_to(args.dest)) not in wanted]
    for p in stale:
        p.unlink()
    print(f"{len(results)} unchanged since the last run, {len(todo)} to process, {len(stale)} stale removed")

    jobs = [(args.src, args.dest, rel, args.factor, args.min_pixels, args.jpeg_quality, args.trim_below) for rel in todo]
    with ProcessPoolExecutor(args.jobs) as pool, progress("Resizing images", total=len(jobs)) as bar:
        for rel, status, old_size, new, trim in pool.map(process, jobs, chunksize=8):
            bar.advance(1, current=str(rel))
            st = (args.src / rel).stat()
            results[rel] = {"mtime": st.st_mtime_ns, "bytes": st.st_size, "status": status,
                            "old": list(old_size), "new": list(new) if new else None,
                            "trim": list(trim) if trim else None}

    record["files"] = {str(rel): e for rel, e in sorted(results.items(), key=lambda kv: str(kv[0]))}
    record_path.write_text(json.dumps(record))

    scaled, small, odd = [], 0, 0
    trims = {}
    before = after = 0
    for rel, e in results.items():
        if e["status"] == "small":
            small += 1
            continue
        (w, h), new = e["old"], e["new"]
        scaled.append(rel)
        if e["trim"] is not None:
            trims[rel] = tuple(e["trim"])
        odd += (Fraction(w) / args.factor).denominator != 1 or (Fraction(h) / args.factor).denominator != 1
        before += w * h * 4
        after += new[0] * new[1] * 4

    write_hook(args.dest, scaled, args.factor, trims)

    changed = f"Scaled {len(scaled)}" if args.factor > 1 else f"Changed {len(scaled)}"
    print(f"{changed}, left {small} untouched; cropped {len(trims)} mostly transparent ones")
    if odd:
        print(f"  {odd} had dimensions not divisible by {args.factor}; they now display up to 1 px larger")
    print(f"Decoded texture size of scaled images: {mib(before)} -> {mib(after)}")
    disk = sum(p.stat().st_size for p in args.dest.rglob("*") if p.is_file())
    print(f"Overlay written to {args.dest} ({mib(disk)} on disk, includes {HOOK_NAME})")


if __name__ == "__main__":
    main()
